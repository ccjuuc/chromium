'use strict';

// Offline, deterministic composition of unchanged vendored CommonJS sources.
// The injected runtime uses these functions directly, without eval or disk I/O.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '../resources/ipc/third_party/readable_stream');
function collect(directory, prefix = '') {
  return fs.readdirSync(directory, {withFileTypes: true}).flatMap(entry => {
    const name = prefix + entry.name;
    return entry.isDirectory() ? collect(path.join(directory, entry.name), name + '/') :
      name.endsWith('.js') && name !== 'bundle.js' ? [name] : [];
  });
}
const source = '// Generated by xenon_overlay/tools/bundle_readable_stream.cjs.\n' +
  '// Third-party copyrights and licenses remain in each source and LICENSE.\n' +
  'function createReadableStreamModules() {\nreturn {\n' +
  collect(root).sort().map(name => JSON.stringify(name) + ': function(require, module, exports) {\n' +
    fs.readFileSync(path.join(root, name), 'utf8').replace(/\r\n/g, '\n') + '\n}').join(',\n') +
  '\n};\n}\n';
const output = path.join(root, 'bundle.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== source)
    throw new Error('readable-stream bundle is stale; run bundle_readable_stream.cjs');
} else fs.writeFileSync(output, source);
