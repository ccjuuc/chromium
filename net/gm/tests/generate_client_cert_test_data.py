"""Regenerate public SM2 selection fixtures using OpenSSL 3.5 or later.

Private keys are temporary and never included in the generated header. These
certificates test selection, not server trust or private-key proof (covered by
the separate live SKF simulator and mutual TLS tests).
"""

import argparse
import base64
import pathlib
import subprocess
import tempfile
import textwrap


def encode_fixture(name, der):
    encoded = base64.b64encode(der.read_bytes()).decode('ascii')
    result = f'\ninline std::vector<uint8_t> {name}() {{\n'
    result += '  auto value = base::Base64Decode(\n'
    result += '\n'.join(f'      "{line}"' for line in textwrap.wrap(encoded, 72))
    result += ');\n  CHECK(value);\n  return {value->begin(), value->end()};\n}\n'
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--openssl', required=True)
    args = parser.parse_args()
    fixtures = [
        ('SigningCertificate', 'SM2', 'digitalSignature', 'clientAuth', 'client', False),
        ('EncryptionCertificate', 'SM2', 'keyEncipherment,dataEncipherment,keyAgreement', 'clientAuth', 'client', False),
        ('ServerCertificate', 'SM2', 'digitalSignature', 'serverAuth', 'client', False),
        ('P256Certificate', 'prime256v1', 'digitalSignature', 'clientAuth', 'client', False),
        ('OtherEncryptionCertificate', 'SM2', 'keyEncipherment', 'clientAuth', 'other', False),
        ('CaSigningCertificate', 'SM2', 'digitalSignature,keyCertSign', 'clientAuth', 'client', True),
        ('BothUsageCertificate', 'SM2', 'digitalSignature,keyEncipherment', 'clientAuth', 'client', False),
        ('NoKeyUsageCertificate', 'SM2', None, 'clientAuth', 'client', False),
    ]
    output = '''// Copyright 2026 The Chromium Authors
// Use of this source code is governed by a BSD-style license that can be
// found in the LICENSE file.

// Generated by generate_client_cert_test_data.py. Public test certificates only.
#ifndef NET_GM_TESTS_CLIENT_CERT_TEST_DATA_H_
#define NET_GM_TESTS_CLIENT_CERT_TEST_DATA_H_

#include <cstdint>
#include <vector>
#include "base/base64.h"
#include "base/check.h"

namespace net::gm::test {
'''
    with tempfile.TemporaryDirectory(prefix='gm-selection-fixtures-') as temp:
        for name, curve, usage, eku, subject, is_ca in fixtures:
            der = pathlib.Path(temp) / 'certificate.der'
            cmd = [args.openssl, 'req', '-x509', '-newkey', 'ec',
                   '-pkeyopt', f'ec_paramgen_curve:{curve}', '-noenc',
                   '-keyout', str(pathlib.Path(temp) / 'key.pem'),
                   '-out', str(der), '-outform', 'DER', '-subj',
                   f'/CN=GM selection test {subject}',
                   '-not_before', '20200101000000Z',
                   '-not_after', '21200101000000Z',
                   '-addext', f'basicConstraints=critical,CA:{str(is_ca).upper()}',
                   '-addext', f'extendedKeyUsage={eku}',
                   '-sm3' if curve == 'SM2' else '-sha256']
            if usage:
                cmd += ['-addext', f'keyUsage=critical,{usage}']
            if curve == 'SM2':
                cmd[cmd.index('-newkey') + 1] = 'SM2'
                del cmd[cmd.index('-pkeyopt'):cmd.index('-pkeyopt') + 2]
                cmd += ['-sigopt', 'distid:1234567812345678']
            subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
            output += encode_fixture(name, der)

        # A real SM2 issuer chain exercises matching a CA above the leaf's
        # immediate issuer. The root and all private keys remain temporary.
        temp_path = pathlib.Path(temp)
        root_cert = temp_path / 'root.pem'
        root_key = temp_path / 'root-key.pem'
        subprocess.run([
            args.openssl, 'req', '-x509', '-newkey', 'SM2', '-noenc',
            '-keyout', str(root_key), '-out', str(root_cert),
            '-subj', '/CN=GM selection chain root',
            '-not_before', '20200101000000Z', '-not_after', '21200101000000Z',
            '-addext', 'basicConstraints=critical,CA:TRUE',
            '-addext', 'keyUsage=critical,keyCertSign,cRLSign',
            '-sm3',
        ], check=True, stdout=subprocess.DEVNULL)
        issuer_cert, issuer_key = root_cert, root_key
        for index, (name, is_ca) in enumerate([
                ('ClientIntermediateCertificate', True),
                ('ChainedSigningCertificate', False)]):
            key = temp_path / f'chain-{index}-key.pem'
            csr = temp_path / f'chain-{index}.csr'
            cert = temp_path / f'chain-{index}.pem'
            extensions = temp_path / f'chain-{index}.cnf'
            usage = 'keyCertSign,cRLSign' if is_ca else 'digitalSignature'
            extensions.write_text(
                f'basicConstraints=critical,CA:{str(is_ca).upper()}\n'
                f'keyUsage=critical,{usage}\n'
                'extendedKeyUsage=clientAuth\n'
                'subjectKeyIdentifier=hash\nauthorityKeyIdentifier=keyid:always\n',
                encoding='ascii')
            subprocess.run([
                args.openssl, 'req', '-new', '-newkey', 'SM2', '-noenc',
                '-keyout', str(key), '-out', str(csr),
                '-subj', f'/CN=GM selection chain {index}',
                '-sm3', '-sigopt', 'distid:1234567812345678',
            ], check=True, stdout=subprocess.DEVNULL)
            subprocess.run([
                args.openssl, 'x509', '-req', '-in', str(csr),
                '-CA', str(issuer_cert), '-CAkey', str(issuer_key),
                '-set_serial', str(100 + index), '-out', str(cert),
                '-not_before', '20200101000000Z', '-not_after', '21200101000000Z',
                '-extfile', str(extensions), '-sm3',
                '-vfyopt', 'distid:1234567812345678',
            ], check=True, stdout=subprocess.DEVNULL)
            der = temp_path / f'chain-{index}.der'
            subprocess.run([
                args.openssl, 'x509', '-in', str(cert), '-outform', 'DER',
                '-out', str(der),
            ], check=True, stdout=subprocess.DEVNULL)
            output += encode_fixture(name, der)
            issuer_cert, issuer_key = cert, key
        subprocess.run([
            args.openssl, 'verify', '-attime', '1800000000',
            '-CAfile', str(root_cert), '-untrusted', str(temp_path / 'chain-0.pem'),
            str(temp_path / 'chain-1.pem'),
        ], check=True, stdout=subprocess.DEVNULL)
    output += '\n}  // namespace net::gm::test\n\n#endif  // NET_GM_TESTS_CLIENT_CERT_TEST_DATA_H_\n'
    pathlib.Path(__file__).with_name('client_cert_test_data.h').write_text(output, encoding='utf-8')


if __name__ == '__main__':
    main()
